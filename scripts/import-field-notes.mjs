/**
 * import-field-notes.mjs
 *
 * Parses docs/integrate-drawingboard-schema.txt for "note:" text on each
 * property. Maps Integrate property names to GlazePro field_keys using the
 * convention: field_key = partType.propertyName.
 *
 * Converts <br> / <br/> / <br /> to newlines.
 * Strips remaining HTML tags (images, tables, divs, etc.).
 *
 * Outputs:
 *   sql/step-q4b-field-notes-import.sql  — UPDATE statements
 *   docs/field-notes-import-report.md    — imported & unmatched report
 *
 * Usage: node scripts/import-field-notes.mjs
 */

import { readFileSync, writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const PROJECT = resolve(__dirname, '..')

const INPUT  = resolve(PROJECT, 'docs/integrate-drawingboard-schema.txt')
const OUTPUT = resolve(PROJECT, 'sql/step-q4b-field-notes-import.sql')
const REPORT = resolve(PROJECT, 'docs/field-notes-import-report.md')

// ── Parse schema file ─────────────────────────────────────────────────────────

const raw = readFileSync(INPUT, 'utf8')
const lines = raw.split('\n')

const entries = []          // { partType, propertyName, noteRaw, fieldKey }
let currentPartType = null

for (const line of lines) {
  // Section header: ## partType — Label (partType) (N properties)
  const sectionMatch = line.match(/^## (\w+)\s+/)
  if (sectionMatch) {
    currentPartType = sectionMatch[1]
    continue
  }

  // Property line with note: - propName | ... | note: ...
  if (!currentPartType) continue
  const noteMatch = line.match(/^- (\w+)\s.*\|\s*note:\s*(.+)$/)
  if (!noteMatch) continue

  const propertyName = noteMatch[1]
  const noteRaw = noteMatch[2].trim()
  const fieldKey = `${currentPartType}.${propertyName}`

  entries.push({ partType: currentPartType, propertyName, noteRaw, fieldKey })
}

// ── Clean note text ───────────────────────────────────────────────────────────

function cleanNote(raw) {
  let text = raw
  // Convert <br>, <br/>, <br /> to newline
  text = text.replace(/<br\s*\/?>/gi, '\n')
  // Strip all remaining HTML tags
  text = text.replace(/<[^>]+>/g, '')
  // Collapse multiple newlines
  text = text.replace(/\n{3,}/g, '\n\n')
  // Trim
  text = text.trim()
  // Skip notes that are just a label with an em-dash and nothing else
  // e.g. "Midrail Height —" or "Casing Thickness — "
  if (text.replace(/[\w\s—\-:.()]/g, '') === '' && /—\s*$/.test(text)) return null
  // Skip notes that are entirely whitespace/punctuation after stripping
  if (text.replace(/[—\-\s]/g, '') === '') return null
  return text
}

// ── Build import list ─────────────────────────────────────────────────────────

const imported = []
const skippedEmpty = []

for (const entry of entries) {
  const cleaned = cleanNote(entry.noteRaw)
  if (!cleaned) {
    skippedEmpty.push(entry)
    continue
  }
  imported.push({ ...entry, noteCleaned: cleaned })
}

// ── Generate SQL ──────────────────────────────────────────────────────────────

function escapeSql(str) {
  return str.replace(/'/g, "''")
}

const sqlLines = [
  '-- ============================================================================',
  '-- step-q4b-field-notes-import.sql — Import field notes from Integrate schema',
  '-- DO NOT RUN — apply through Supabase SQL Editor after review',
  '-- Run order: after step-q4-field-notes.sql',
  '-- ============================================================================',
  '',
  '-- Generated by: node scripts/import-field-notes.mjs',
  `-- Source: docs/integrate-drawingboard-schema.txt`,
  `-- Date: ${new Date().toISOString().slice(0, 10)}`,
  `-- Entries: ${imported.length} imported, ${skippedEmpty.length} skipped (empty after cleaning)`,
  '',
  'BEGIN;',
  '',
]

for (const entry of imported) {
  sqlLines.push(
    `UPDATE public.default_field_definitions`,
    `  SET info_note = '${escapeSql(entry.noteCleaned)}'`,
    `  WHERE field_key = '${escapeSql(entry.fieldKey)}';`,
    '',
  )
}

sqlLines.push('COMMIT;')
sqlLines.push('')

writeFileSync(OUTPUT, sqlLines.join('\n'), 'utf8')

// ── Generate report ───────────────────────────────────────────────────────────

const reportLines = [
  '# Field Notes Import Report',
  '',
  `Generated: ${new Date().toISOString().slice(0, 10)}`,
  '',
  `## Summary`,
  '',
  `- **Source**: docs/integrate-drawingboard-schema.txt`,
  `- **Total properties with notes**: ${entries.length}`,
  `- **Imported** (non-empty after cleaning): ${imported.length}`,
  `- **Skipped** (empty after cleaning): ${skippedEmpty.length}`,
  '',
  '## Imported',
  '',
  '| field_key | Note (first 80 chars) |',
  '|---|---|',
]

for (const entry of imported) {
  const preview = entry.noteCleaned.replace(/\n/g, ' ').slice(0, 80)
  reportLines.push(`| \`${entry.fieldKey}\` | ${preview} |`)
}

reportLines.push('')
reportLines.push('## Skipped (empty after cleaning)')
reportLines.push('')

if (skippedEmpty.length === 0) {
  reportLines.push('None.')
} else {
  reportLines.push('| field_key | Raw note |')
  reportLines.push('|---|---|')
  for (const entry of skippedEmpty) {
    reportLines.push(`| \`${entry.fieldKey}\` | ${entry.noteRaw.slice(0, 80)} |`)
  }
}

reportLines.push('')

writeFileSync(REPORT, reportLines.join('\n'), 'utf8')

console.log(`Imported: ${imported.length}`)
console.log(`Skipped (empty): ${skippedEmpty.length}`)
console.log(`SQL:    ${OUTPUT}`)
console.log(`Report: ${REPORT}`)
