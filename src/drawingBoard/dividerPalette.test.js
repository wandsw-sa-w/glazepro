// dividerPalette.test.js — Step AW
//
// Integrate's Transom / Mullion palette has two behaviours, and these test the
// second: with an OPENING selected, the "1x2" and "2x1" tiles split THAT
// opening, the new divider stopping at whatever bounds it. That is how
// Integrate draws TC1 and TC3, so the trees that come out have to be the Step
// AV benchmark geometry.
//
// The whole-frame tiles call `applyDividers`, which is the function the old
// hover grid called and is covered in gridActions.test.js — the palette
// changed what the dialog looks like, not what it does.

import { describe, it, expect } from 'vitest'
import {
  buildCasementFrame, openingNodes, openingMatrixIndex, openingTypeLabel,
  setCasementOperation, applyFanlightBottomRails, resizeCasementFrame,
} from './casementOpenings.js'
import {
  applyDividers, splitOpening, removeDivider, makeDividersEqual,
} from './gridActions.js'
import { assertSaveable } from './containment.js'
import { frameCells, frameInterior } from '../pricing/casementGeometry.js'
import { BENCHMARK_TC1, BENCHMARK_TC3 } from '../pricing/benchmarks/fixtureCasement.js'

// Profile 2 (casement), full field keys for the build and short keys for the
// picker, exactly as DrawingBoard passes them.
const ROWS = [
  ['assemblyFramePart.leftWidth', '37'], ['assemblyFramePart.rightWidth', '37'],
  ['assemblyFramePart.topHeight', '47'], ['assemblyFramePart.bottomHeight', '47'],
  ['assemblyFramePart.frameDepth', '96'], ['assemblyFramePart.frameHeadStopSize', '20'],
  ['assemblyFramePart.frameStileStopSize', '20'], ['assemblyFramePart.cillStopSize', '20'],
  ['assemblyFramePart.cillAngle', '6'],
  ['cillPart.height', '47'], ['cillPart.depth', '128'],
  ['mullionPart.thicknessInFrameSolid', '27'], ['mullionPart.mullionStopSize', '20'],
  ['casementSashPart.thickness', '54'], ['casementSashPart.topHeight', '62'],
  ['casementSashPart.leftWidth', '62'], ['casementSashPart.rightWidth', '62'],
  ['casementSashPart.bottomHeight', '83'],
  ['casementSashPart.defaultFanlightBottomHeight', '62'],
  ['casementSashPart.mechanicalClearanceLeft', '4'], ['casementSashPart.mechanicalClearanceRight', '4'],
  ['casementSashPart.mechanicalClearanceTop', '4'], ['casementSashPart.mechanicalClearanceBottom', '4'],
  ['casementSashPart.btmRailShapeId', 'square'],
  ['glassPart.defaultDoubleGlazingRebateWidthForSash', '16'],
  ['glassPart.defaultDoubleGlazingTolerance', '2'],
  ['glassPart.defaultDirGuStopSize', '20'],
  ['glassPart.defaultDoubleGlazingRebateWidthForDirGU', '20'],
  ['glassPart.defaultDoubleGlazingToleranceForDirGU', '2'],
].map(([field_key, default_value]) => ({ profile_id: 2, field_key, default_value }))

const PICKER_PV = { thicknessInFrameSolid: 27, mullionStopSize: 20 }

const frameOf = t => t.children.find(c => c.part_type === 'assemblyFramePart')
const dividersOf = t => (frameOf(t).children ?? [])
  .filter(c => c.part_type === 'mullionPart' || c.part_type === 'transomPart')
const shapeOf = t => frameCells(t).map(c => [c.col, c.row, c.colSpan, c.rowSpan])
const sizesOf = t => frameCells(t).map(c => [c.width, c.height])
const labelsOf = t => openingNodes(t).map(n => openingMatrixIndex(t, n))

function setOffsetOf(tree, key, offset) {
  return {
    ...tree,
    children: tree.children.map(c => c.part_type !== 'assemblyFramePart' ? c : ({
      ...c,
      children: c.children.map(g => g.key !== key ? g
        : ({ ...g, values: { ...g.values, offset } })),
    })),
  }
}

function newFrame(width, height, openings = ['opening_casement']) {
  const { tree, missing } = buildCasementFrame(ROWS, {
    width, height, openings, product: 'casement',
  })
  expect(missing, 'profile values the build could not resolve').toEqual([])
  return tree
}

function grid(tree, cols, rows) {
  const i = frameInterior(tree)
  return applyDividers(tree, frameOf(tree).key, cols, rows, i.width, i.height, PICKER_PV, 'solid')
}

/** One palette tile with an opening selected. */
function pickTile(tree, openingKey, cols, rows) {
  const axis = rows > cols ? 'transom' : 'mullion'
  const next = splitOpening(tree, frameOf(tree).key, openingKey, axis, PICKER_PV)
  return applyFanlightBottomRails(next, ROWS).tree
}

// ── TC1 and TC3, the way Integrate draws them ────────────────────────────────

describe('Step AW — the two tiles split the selected opening', () => {
  it('TC1: the fanlight template, then 2x1 on the LOWER opening', () => {
    // "Single Flush Casement with Fanlight" is a 1 x 2 casement frame — the
    // tree sql/step-ar1 stores was generated by exactly this code — resized
    // to TC1's 1105 x 1405 with the transom at TC1's 301.
    let tree = grid(newFrame(1105, 1405), 1, 2)
    const transom = dividersOf(tree)[0]
    tree = setOffsetOf(tree, transom.key, 301)
    tree = setCasementOperation(tree, openingNodes(tree)[0].key, 'top_hung').tree
    expect(shapeOf(tree)).toEqual([[0, 0, 1, 1], [0, 1, 1, 1]])

    // Select the LOWER opening (A2) and click "2x1"
    const lower = openingNodes(tree)[1]
    tree = pickTile(tree, lower.key, 2, 1)

    // The mullion stops at the transom and runs to the cill
    const mullion = dividersOf(tree).find(d => d.part_type === 'mullionPart')
    expect(mullion.values.startDivider).toBe(transom.key)
    expect(mullion.values.endDivider).toBe('0')
    // It went in the MIDDLE of the opening: (1031 - 27) / 2 = 502
    expect(mullion.values.offset).toBe(502)

    // The surveyor types TC1's 493, and the tree is TC1's
    tree = setOffsetOf(tree, mullion.key, 493)
    tree = setCasementOperation(tree, openingNodes(tree)[1].key, 'left_hand_hung').tree
    tree = setCasementOperation(tree, openingNodes(tree)[2].key, 'right_hand_hung').tree

    expect(shapeOf(tree)).toEqual(shapeOf(BENCHMARK_TC1.tree))
    expect(sizesOf(tree)).toEqual(sizesOf(BENCHMARK_TC1.tree))
    expect(sizesOf(tree)).toEqual([[1031, 301], [493, 983], [511, 983]])
    expect(labelsOf(tree)).toEqual(['A1', 'A2', 'B2'])
    expect(openingNodes(tree).map(n => n.values.operation))
      .toEqual(['top_hung', 'left_hand_hung', 'right_hand_hung'])
    expect(() => assertSaveable(tree)).not.toThrow()
  })

  it('TC3: 2x1 on the frame, then 1x2 on column B', () => {
    let tree = grid(newFrame(1205, 1295), 2, 1)
    const mullion = dividersOf(tree)[0]
    tree = setOffsetOf(tree, mullion.key, 543)

    // Select column B (the right-hand opening) and click "1x2"
    const columnB = openingNodes(tree)[1]
    tree = pickTile(tree, columnB.key, 1, 2)

    const transom = dividersOf(tree).find(d => d.part_type === 'transomPart')
    expect(transom.values.startDivider).toBe(mullion.key)
    expect(transom.values.endDivider).toBe('0')
    // The middle of the opening on the TRANSOM's own axis: column B is the
    // full height at this point, so (1201 - 27) / 2 = 587, not half of 354.
    expect(transom.values.offset).toBe(587)

    tree = setOffsetOf(tree, transom.key, 354)
    tree = setCasementOperation(tree, openingNodes(tree)[0].key, 'left_hand_hung').tree
    tree = setCasementOperation(tree, openingNodes(tree)[1].key, 'top_hung').tree
    tree = setCasementOperation(tree, openingNodes(tree)[2].key, 'fix').tree

    expect(shapeOf(tree)).toEqual(shapeOf(BENCHMARK_TC3.tree))
    expect(sizesOf(tree)).toEqual(sizesOf(BENCHMARK_TC3.tree))
    expect(sizesOf(tree)).toEqual([[543, 1201], [561, 354], [561, 820]])
    expect(labelsOf(tree)).toEqual(['A1', 'B1', 'B2'])
    // A1 runs the full height, so it is not a fanlight and keeps the 83 rail
    expect(openingNodes(tree).map(n => openingTypeLabel(tree, n)))
      .toEqual(['Casement Sash', 'Fanlight', 'Casement Sash'])
    expect(openingNodes(tree).map(n => n.values.bottomHeight)).toEqual([83, 62, 83])
    expect(() => assertSaveable(tree)).not.toThrow()
  })

  it('a SPANNING opening can be split, and the divider stops at the transom', () => {
    // TC1's fanlight runs across both columns. "2x1" on it puts a mullion
    // through the top row only, stopping at the transom BELOW it.
    let tree = grid(newFrame(1105, 1405), 1, 2)
    const transom = dividersOf(tree)[0]
    tree = setOffsetOf(tree, transom.key, 301)
    tree = pickTile(tree, openingNodes(tree)[1].key, 2, 1)
    expect(shapeOf(tree)).toEqual([[0, 0, 2, 1], [0, 1, 1, 1], [1, 1, 1, 1]])

    const fanlight = openingNodes(tree)[0]
    tree = pickTile(tree, fanlight.key, 2, 1)

    // four openings, and the new mullion exists ABOVE the transom
    expect(openingNodes(tree).length).toBe(4)
    const topMullion = dividersOf(tree)
      .filter(d => d.part_type === 'mullionPart')
      .find(d => d.values.endDivider === transom.key)
    expect(topMullion, 'a mullion ending at the transom').toBeTruthy()
    expect(topMullion.values.startDivider).toBe('0')
    // Both mullions went in at the middle of what they split, so they are
    // stacked at 502 until the surveyor moves one. They are two separate
    // dividers, as Integrate's model has them — not one full-height mullion.
    expect(topMullion.values.offset).toBe(502)
    expect(dividersOf(tree).filter(d => d.part_type === 'mullionPart').length).toBe(2)

    // Give the top one its own offset and the window reads correctly: the
    // top row splits at 300, the bottom row at 493, and each row's other
    // cell spans the column slot the mullion that made it does not reach.
    tree = setOffsetOf(tree, topMullion.key, 300)
    expect(shapeOf(tree)).toEqual([[0, 0, 1, 1], [1, 0, 2, 1], [0, 1, 2, 1], [2, 1, 1, 1]])
    expect(openingNodes(tree).length).toBe(4)
    expect(() => assertSaveable(tree)).not.toThrow()
  })

  it('splitting one opening of a 2 x 2 keeps every opening on its own cell', () => {
    // The openings list and the cells are matched by POSITION everywhere, so
    // this is the case that would mislabel and mis-size a window if the copy
    // went in the wrong place: splitting B1 puts the new cell THIRD, not last.
    let tree = grid(newFrame(1299, 1499), 2, 2)
    const named = openingNodes(tree).map((n, i) => ({ key: n.key, was: labelsOf(tree)[i] }))
    expect(named.map(n => n.was)).toEqual(['A1', 'B1', 'A2', 'B2'])

    tree = pickTile(tree, named[1].key, 1, 2)   // a transom through B1 only

    // Five cells: A spans the two top rows, B is split, the bottom row is as
    // it was. The surveyor's own openings keep their places.
    expect(shapeOf(tree)).toEqual([[0, 0, 1, 2], [1, 0, 1, 1], [1, 1, 1, 1], [0, 2, 1, 1], [1, 2, 1, 1]])
    expect(labelsOf(tree)).toEqual(['A1', 'B1', 'B2', 'A3', 'B3'])
    const keys = openingNodes(tree).map(n => n.key)
    expect(keys[0]).toBe(named[0].key)   // A1 is still A1's part
    expect(keys[1]).toBe(named[1].key)   // the split opening keeps the top half
    expect(keys[2]).not.toBe(named[1].key)   // the copy is the new lower half
    expect(keys[3]).toBe(named[2].key)   // the old A2 is now A3, same part
    expect(keys[4]).toBe(named[3].key)
    expect(new Set(keys).size).toBe(5)
    expect(() => assertSaveable(tree)).not.toThrow()
  })

  it('a selection that is not an opening of the frame changes nothing', () => {
    const tree = grid(newFrame(1200, 1300), 2, 1)
    expect(splitOpening(tree, frameOf(tree).key, 'nosuchkey', 'mullion', PICKER_PV)).toBe(tree)
    const cill = frameOf(tree).children.find(c => c.part_type === 'cillPart')
    expect(splitOpening(tree, frameOf(tree).key, cill.key, 'mullion', PICKER_PV)).toBe(tree)
  })

  it('without the profile thickness nothing is added, and it says why', () => {
    const tree = grid(newFrame(1200, 1300), 1, 2)
    expect(() => splitOpening(tree, frameOf(tree).key,
      openingNodes(tree)[0].key, 'mullion', {}))
      .toThrow(/thicknessInFrameSolid/)
  })

  it('what Step AV made still works: remove merges, resize keeps the span', () => {
    let tree = grid(newFrame(1105, 1405), 1, 2)
    const transom = dividersOf(tree)[0]
    tree = setOffsetOf(tree, transom.key, 301)
    tree = pickTile(tree, openingNodes(tree)[1].key, 2, 1)

    const mullion = dividersOf(tree).find(d => d.part_type === 'mullionPart')
    const merged = removeDivider(tree, frameOf(tree).key, mullion.key)
    expect(openingNodes(merged).length).toBe(2)
    expect(shapeOf(merged)).toEqual([[0, 0, 1, 1], [0, 1, 1, 1]])

    const wider = resizeCasementFrame(tree, { width: 1305, height: 1505 }).tree
    expect(shapeOf(wider)).toEqual([[0, 0, 2, 1], [0, 1, 1, 1], [1, 1, 1, 1]])
    expect(frameCells(wider)[0].width).toBe(frameInterior(wider).width)
  })
})

// ── Divider Spacing ──────────────────────────────────────────────────────────

describe('Step AW — Make Widths Equal / Make Heights Equal', () => {
  it('evens up the columns, leaving everything else alone', () => {
    let tree = grid(newFrame(1205, 1295), 2, 1)
    const mullion = dividersOf(tree)[0]
    tree = setOffsetOf(tree, mullion.key, 543)
    expect(sizesOf(tree).map(c => c.width ?? c[0])).toEqual([543, 561])

    const even = makeDividersEqual(tree, frameOf(tree).key, 'widths')
    // interior 1131 less the 27 mullion, halved: 552 each
    expect(sizesOf(even)).toEqual([[552, 1201], [552, 1201]])
    expect(dividersOf(even).length).toBe(1)
    expect(openingNodes(even).map(n => n.key))
      .toEqual(openingNodes(tree).map(n => n.key))
  })

  it('evens up the rows', () => {
    let tree = grid(newFrame(1105, 1405), 1, 2)
    tree = setOffsetOf(tree, dividersOf(tree)[0].key, 301)
    const even = makeDividersEqual(tree, frameOf(tree).key, 'heights')
    // interior 1311 less the 27 transom, halved: 642 each
    expect(sizesOf(even)).toEqual([[1031, 642], [1031, 642]])
  })

  it('a SHORT divider is re-spaced too, and still stops where it stopped', () => {
    // TC1: the mullion exists in the bottom row only. Evening the widths
    // moves it to the middle without making it a full-height mullion.
    let tree = grid(newFrame(1105, 1405), 1, 2)
    const transom = dividersOf(tree)[0]
    tree = setOffsetOf(tree, transom.key, 301)
    tree = pickTile(tree, openingNodes(tree)[1].key, 2, 1)
    tree = setOffsetOf(tree, dividersOf(tree).find(d => d.part_type === 'mullionPart').key, 493)

    const even = makeDividersEqual(tree, frameOf(tree).key, 'widths')
    const mullion = dividersOf(even).find(d => d.part_type === 'mullionPart')
    expect(mullion.values.offset).toBe(502)          // (1031 - 27) / 2
    expect(mullion.values.startDivider).toBe(transom.key)
    expect(shapeOf(even)).toEqual([[0, 0, 2, 1], [0, 1, 1, 1], [1, 1, 1, 1]])
    expect(sizesOf(even)).toEqual([[1031, 301], [502, 983], [502, 983]])
  })

  it('a frame with nothing to even up is returned untouched', () => {
    const tree = newFrame(1200, 1300)
    expect(makeDividersEqual(tree, frameOf(tree).key, 'widths')).toBe(tree)
    expect(makeDividersEqual(tree, frameOf(tree).key, 'heights')).toBe(tree)
    expect(makeDividersEqual(tree, 'nosuchframe', 'widths')).toBe(tree)
  })
})
