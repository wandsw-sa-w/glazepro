-- Run by Nathan in the Supabase SQL editor. Safe to re-run.
--
-- Facts: docs/integrate-L31115-stormproof.txt (reviewer, 13 Oct 2026).
-- Nathan (13 Oct): a stormproof window is stormproof THROUGHOUT, and GlazePro
-- uses a 76 mm sash bottom rail on every stormproof sash, fanlights included.
--
-- I COULD NOT READ THE LIVE ROWS. The brief asked me to check them with
-- /dev/sql, but claude_readonly_query admits only
-- nathan.smith@wandsworthsashwindows.com and my only credentials are the
-- smoke-test user, so it answers "not allowed for this user". Every statement
-- below is therefore written to be SAFE WHATEVER IS THERE: it adds only what
-- is missing and never overwrites a value that already exists. Section 0's
-- queries print what was found, so the key spellings can be confirmed.
--
-- WHY THE CASEMENT PROFILE AND NOT A SEPARATE STORMPROOF ONE: a drawing loads
-- exactly one profile (its default_profile_id), and converting a window to
-- stormproof AND BACK needs both sets of sections available at once. Separate
-- profiles would mean changing a drawing's profile mid-edit and losing the
-- flush values to restore from. Integrate does the same — its casement profile
-- carries both the flush and the stormproof frame defaults — and GlazePro's
-- casement profile already holds casementSashPart.stormProofOverlap and
-- .stormProofLipThickness (sql/step-aq3 reclassified both as profile
-- settings), so these keys join a set that is already there.
-- =============================================================================

-- ── 0. What is already there (run these first; they change nothing) ─────────
SELECT code, label, is_active, applies_to FROM public.reference_options
WHERE  category = 'sash_type' ORDER BY sort_order;

SELECT v.field_key, v.default_value
FROM   public.default_profile_values v
JOIN   public.default_profiles p ON p.id = v.profile_id
WHERE  p.code = 'casement' AND v.field_key ILIKE '%storm%'
ORDER  BY v.field_key;

BEGIN;

-- ── 1. The sash type ───────────────────────────────────────────────────────
-- Integrate typeId 9 "Storm Proof". The brief says 'stormproof' is the live
-- sash_type code; this adds it ONLY if it is absent, and widens applies_to to
-- casementSashPart if the row exists but is limited to other part types (the
-- shape sql/step-ar2 used for the 'fix' operation).
INSERT INTO public.reference_options (category, code, label, sort_order, is_active, applies_to)
SELECT 'sash_type', 'stormproof', 'Stormproof', 30, TRUE, '{casementSashPart}'
WHERE  NOT EXISTS (
  SELECT 1 FROM public.reference_options
  WHERE  category = 'sash_type' AND code = 'stormproof'
);

UPDATE public.reference_options
SET    applies_to = array_append(applies_to, 'casementSashPart')
WHERE  category = 'sash_type' AND code = 'stormproof'
  AND  cardinality(applies_to) > 0
  AND  NOT ('casementSashPart' = ANY (applies_to));

-- ── 2. The stormproof sections on the casement profile ─────────────────────
-- Integrate's own values, from every drawing the reviewer read. ON CONFLICT
-- DO NOTHING so a key Integrate's import already created keeps ITS value —
-- these are Integrate's figures, not mine to overwrite.
--
-- The sash THICKNESS (54), head and stiles (62) and clearances (4) are the
-- same stormproof as flush, so they are not duplicated here: the code reads
-- them from the existing casementSashPart keys.
INSERT INTO public.default_profile_values (profile_id, field_key, default_value)
SELECT p.id, v.field_key, v.default_value
FROM   public.default_profiles p
CROSS  JOIN (VALUES
  ('assemblyFramePart.stormProofLeftWidth',      '41'),   -- jambs 41 (+15 stop = 56 overall)
  ('assemblyFramePart.stormProofRightWidth',     '41'),
  ('assemblyFramePart.stormProofTopHeight',      '41'),   -- head
  ('assemblyFramePart.stormProofBottomHeight',   '56'),
  ('assemblyFramePart.stormProofFrameDepth',     '69'),
  ('assemblyFramePart.stormProofHeadStopSize',   '15'),
  ('assemblyFramePart.stormProofStileStopSize',  '15'),
  ('assemblyFramePart.stormProofCillStopSize',   '15'),
  ('cillPart.stormProofHeight',                  '56'),   -- 71 finished with its stop
  ('cillPart.stormProofDepth',                   '69'),
  ('casementSashPart.stormProofBottomHeight',    '76'),   -- Nathan, 13 Oct: 76 everywhere
  ('casementSashPart.stormProofOverlap',          '7')    -- DRAWN only; nothing prices it
) AS v(field_key, default_value)
WHERE  p.code = 'casement'
ON CONFLICT (profile_id, field_key) DO NOTHING;

-- ── 3. The "Single Stormproof Casement" template ───────────────────────────
-- Integrate's template 21 is 499 x 999 with one LH opener. The tree was
-- GENERATED by the board's own buildCasementFrame({ stormproof: true }), so
-- the template is exactly what the board builds. Product is looked up BY
-- LABEL (the `product` codes are not in the repository) and the script fails
-- loudly rather than writing a code that would look set and still fail the
-- required-field check. No stored ironmongery: the default rules price it.
DO $$
DECLARE
  _profile_id    bigint;
  _casement_code text;
  _tree          jsonb := '{"key":"drawingItem_1","part_type":"drawingItemPart","values":{"typeOfWork":"complete_new","frameMaterialId":"softwood","sashMaterialId":"softwood","cillMaterialId":"utile","quantity":1},"children":[{"key":"paintAndIronmongery_2","part_type":"paintAndIronmongeryPart","values":{"internalFinish":"clean_white","externalFinish":"clean_white","cillFinish":"clean_white","cutOutBrickReveal":false,"ironmongeryFinish":"PB","isCasementMpls":true},"children":[]},{"key":"notes_3","part_type":"notesPart","values":{},"children":[]},{"key":"price_4","part_type":"pricePart","values":{},"children":[]},{"key":"assemblyFrame_5","part_type":"assemblyFramePart","values":{"width":499,"height":999,"leftWidth":41,"rightWidth":41,"topHeight":41,"bottomHeight":56,"frameDepth":69,"jambType":"solid_profiled","frameHeadStopSize":15,"frameStileStopSize":15,"cillStopSize":15,"cillAngle":6,"rakeFrame":false,"archHead":false},"children":[{"key":"casementSash_6","part_type":"casementSashPart","values":{"operation":"left_hand_hung","casementTypeId":"stormproof","thickness":54,"topHeight":62,"leftWidth":62,"rightWidth":62,"bottomHeight":76,"stormProofOverlap":7,"mechanicalClearanceLeft":4,"mechanicalClearanceRight":4,"mechanicalClearanceTop":4,"mechanicalClearanceBottom":4,"btmRailShapeId":"square","toBeReplaced":true},"children":[{"key":"glass_7","part_type":"glassPart","values":{"glazingId":"double_glazing","isIndividualPanes":false,"internalGlassPartNo":"GL100010","externalGlassPartNo":"GL100080","glazingRebateWidth":16,"glazingTolerance":2},"children":[]}]},{"key":"cill_8","part_type":"cillPart","values":{"height":56,"depth":69},"children":[]}]}]}'::jsonb;
BEGIN
  SELECT id INTO _profile_id FROM public.default_profiles
  WHERE code = 'casement' AND is_active = TRUE;
  IF _profile_id IS NULL THEN
    RAISE EXCEPTION 'No active default_profiles row with code ''casement''';
  END IF;

  SELECT code INTO _casement_code FROM public.reference_options
  WHERE category = 'product' AND lower(label) = 'casement' AND is_active
  ORDER BY sort_order LIMIT 1;
  IF _casement_code IS NULL THEN
    RAISE EXCEPTION 'No active product option labelled ''Casement'' — run: SELECT code, label FROM reference_options WHERE category = ''product'' ORDER BY sort_order;';
  END IF;

  _tree := jsonb_set(_tree, '{values,product}', to_jsonb(_casement_code), true);

  IF NOT EXISTS (SELECT 1 FROM public.drawing_templates WHERE name = 'Single Stormproof Casement') THEN
    INSERT INTO public.drawing_templates
      (name, family, group_name, window_type, default_profile_id, tree, sort_order, is_active)
    VALUES ('Single Stormproof Casement', 'casement', 'Casement', 'Casement',
            _profile_id, _tree, 40, TRUE);
    RAISE NOTICE 'Step AU-1: stormproof template created';
  ELSE
    UPDATE public.drawing_templates
    SET tree = _tree, default_profile_id = _profile_id, updated_at = now()
    WHERE name = 'Single Stormproof Casement';
    RAISE NOTICE 'Step AU-1: stormproof template updated in place';
  END IF;
END $$;

COMMIT;

-- ── 4. Checks ──────────────────────────────────────────────────────────────

-- 4a. Expect a 'stormproof' sash_type whose applies_to covers casementSashPart
--     (or is empty, meaning "any part").
SELECT code, label, sort_order, is_active, applies_to
FROM   public.reference_options WHERE category = 'sash_type' ORDER BY sort_order;

-- 4b. Expect the twelve stormproof keys with the values above. If a row shows
--     a DIFFERENT value, Integrate's import already had that key — say so and
--     its spelling goes to the front of STORMPROOF_CANDIDATES in
--     src/drawingBoard/casementOpenings.js, which is the only change needed.
SELECT v.field_key, v.default_value
FROM   public.default_profile_values v
JOIN   public.default_profiles p ON p.id = v.profile_id
WHERE  p.code = 'casement' AND v.field_key ILIKE '%stormProof%'
ORDER  BY v.field_key;

-- 4c. Expect five casement templates, the stormproof one last (sort 40).
SELECT name, sort_order, is_active,
       tree #>> '{values,product}'  AS product_code,
       tree #>> '{values,quantity}' AS quantity
FROM   public.drawing_templates WHERE family = 'casement' ORDER BY sort_order;

-- 4d. The stormproof template's own shape: frame 41 / 41 / 69 with 15 stops,
--     one sash at 76 with overlap 7 and sash type 'stormproof'.
SELECT t.name,
       t.tree #>> '{children,3,values,leftWidth}'  AS jamb,
       t.tree #>> '{children,3,values,topHeight}'  AS head,
       t.tree #>> '{children,3,values,frameDepth}' AS depth,
       (SELECT jsonb_agg(v) FROM jsonb_path_query(t.tree, '$.**.values.bottomHeight') v)      AS bottom_rails,
       (SELECT jsonb_agg(v) FROM jsonb_path_query(t.tree, '$.**.values.stormProofOverlap') v) AS overlaps,
       (SELECT jsonb_agg(v) FROM jsonb_path_query(t.tree, '$.**.values.casementTypeId') v)    AS sash_types
FROM   public.drawing_templates t
WHERE  t.name = 'Single Stormproof Casement';


